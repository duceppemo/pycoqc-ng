# -*- coding: utf-8 -*-

#~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~IMPORTS~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~#

# Standard library imports
from collections import Counter, OrderedDict
import warnings

# Third party imports
import pandas as pd
import pysam as ps

# Local lib import
from pycoQC.common import (
    dict_to_str,
    expand_file_names,
    get_logger,
    merge_files_to_df,
    pycoQCError)

#~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~GLOBAL SETTINGS~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~#

# Silence futurewarnings
warnings.filterwarnings("ignore", category=FutureWarning)

#~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~MAIN CLASS~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~#
class pycoQC_parse():

    #~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~INIT METHOD~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~#
    def __init__(self,
                 summary_file: str,
                 barcode_file: str = "",
                 bam_file: str = "",
                 runid_list: list = (),
                 filter_calibration: bool = False,
                 filter_duplicated: bool = False,
                 min_barcode_percent: float = 0.1,
                 cleanup: bool = True,
                 verbose: bool = False,
                 quiet: bool = False):
        """
        Parse Albacore sequencing_summary.txt file and clean-up the data
        * summary_file
            Path to the sequencing_summary generated by Albacore 1.0.0 +(read_fast5_basecaller.py) / Guppy 2.1.3+(guppy_basecaller).
            One can also pass multiple space separated file paths or a UNIX style regex matching multiple files
        * barcode_file
            Path to the barcode_file generated by Guppy 2.1.3+(guppy_barcoder) or Deepbinner 0.2.0+. This is not a required file.
            One can also pass multiple space separated file paths or a UNIX style regex matching multiple files
        * bam_file
            Path to a Bam file corresponding to reads in the summary_file. Preferably aligned with Minimap2
            One can also pass multiple space separated file paths or a UNIX style regex matching multiple files
        * runid_list
            Select only specific runids to be analysed. Can also be used to force pycoQC to order the runids for
            temporal plots, if the sequencing_summary file contain several sucessive runs. By default pycoQC analyses
            all the runids in the file and uses the runid order as defined in the file.
        * filter_calibration
            If True read flagged as calibration strand by the software are removed
        * filter_duplicated
            If True duplicated read_ids are removed but the first occurence is kept(Guppy sometimes outputs the same read multiple times)
        * min_barcode_percent
            Minimal percent of total reads to retain barcode label. If below the barcode value is set as `unclassified`.
        """

        # Set logging level
        self.logger = get_logger(name=__name__, verbose=verbose, quiet=quiet)

        # Save self variables
        self.runid_list = runid_list
        self.filter_calibration = filter_calibration
        self.filter_duplicated = filter_duplicated
        self.min_barcode_percent = min_barcode_percent
        self.cleanup = cleanup

        # Init object counter
        self.counter = OrderedDict()

        # Check input files
        self.logger.warning("Check input data files")

        # Expand file names and test readability
        self.summary_files_list = expand_file_names(summary_file)
        self.logger.debug("\t\tSequencing summary files found: {}".format(" ".join(self.summary_files_list)))
        self.counter["Summary files found"] = len(self.summary_files_list)

        if barcode_file:
            self.barcode_files_list = expand_file_names(barcode_file)
            self.logger.debug("\t\tBarcode files found: {}".format(" ".join(self.barcode_files_list)))
            self.counter["Barcode files found"] = len(self.barcode_files_list)
        else:
            self.barcode_files_list = []

        if bam_file:
            self.bam_file_list = expand_file_names(bam_file, bam_check=True)
            self.logger.debug("\t\tBam files found: {}".format(" ".join(self.bam_file_list)))
            self.counter["Bam files found"] = len(self.bam_file_list)
        else:
            self.bam_file_list = []

        self.logger.warning("Parse data files")
        # Filled by _parse_summary; defined here so it always exists.
        self.run_metadata = OrderedDict()
        summary_reads_df = self._parse_summary()
        barcode_reads_df = self._parse_barcode()
        bam_reads_df, self.alignments_df, self.ref_len_dict = self._parse_bam()

        self.logger.warning("Merge data")
        self.reads_df = self._merge_reads_df(summary_reads_df, barcode_reads_df, bam_reads_df)

        # Cleanup data
        if self.cleanup:
            self.logger.warning("Cleaning data")
            self.reads_df = self._clean_reads_df(self.reads_df)

    def __str__(self):
        return dict_to_str(self.counter)

    def __repr__(self):
        return "[{}]\n".format(self.__class__.__name__)

    #~~~~~~~~~~~~~~~~~~~~~~~~~~~~~PRIVATE METHODS~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~#

    def _require_reads(self, df, step):
        """Stop when a step has left too little to report on.

        The plots need more than one read, so a single read file stops here
        too; saying "no valid read left" when one was never discarded sent
        people looking for a filtering bug that was not there.
        """
        if len(df) > 1:
            return
        if len(df) == 0:
            raise pycoQCError(
                "No reads left after {}.".format(step))
        raise pycoQCError(
            "Only one read left after {}. pycoQC needs at least two reads "
            "to describe a run.".format(step))

    def _parse_summary(self):
        """"""
        self.logger.debug("\tParse summary files")
        df = merge_files_to_df(self.summary_files_list, self.logger)

        if self.cleanup:
            # Standardise col names for all types of files
            self.logger.debug("\tRename summary sequencing columns")
            # Several spellings mean the same thing, and a file can carry
            # more than one of them: a 1D2 summary has both the template and
            # the 2d length. Renaming them all onto one name left the frame
            # with duplicate labels, and pandas then answered an ordinary
            # question about that column with "The truth value of a Series
            # is ambiguous", which says nothing about the file. Each group
            # below is in order of preference, and only the first spelling
            # present is kept.
            column_groups = (
                ("read_len", ("sequence_length_template", "sequence_length_2d",
                              "sequence_length", "read_len")),
                ("mean_qscore", ("mean_qscore_template", "mean_qscore_2d",
                                 "mean_qscore")),
                ("calibration", ("calibration_strand_genome_template",
                                 "calibration_strand_genome", "calibration")),
                ("barcode", ("barcode_arrangement", "barcode")),
                ("%GC", ("gc_percent", "%GC")))

            rename_colmanes = {}
            for target, sources in column_groups:
                present = [c for c in sources if c in df]
                if not present:
                    continue
                if len(present) > 1:
                    self.logger.debug(
                        "\t\tUsing {} for {}, ignoring {}".format(
                            present[0], target, ", ".join(present[1:])))
                    df = df.drop(columns=present[1:])
                if present[0] != target:
                    rename_colmanes[present[0]] = target

            df = df.rename(columns=rename_colmanes)

            # Verify the required and optional columns, Drop unused fields
            self.logger.debug("\tVerifying fields and discarding unused columns")
            self.run_metadata = self._collect_run_metadata(df)

            df = self._select_df_columns(
                df=df,
                required_colnames=["read_id", "read_len", "mean_qscore"],
                # Run metadata is optional: a plain fastq, an Illumina run or
                # any basecaller output without ONT headers carries none of
                # it. Plots that need a missing column are skipped.
                optional_colnames=["run_id", "channel", "start_time",
                                   "calibration", "barcode", "%GC"])

        # Collect stats
        n = len(df)
        self.logger.debug("\t\t{:,} reads found in initial file".format(n))
        self.counter["Initial reads"] = n

        return df

    # Columns that describe the run rather than a read. Several spellings
    # exist because the basecallers and the converters disagree, and the
    # first one present wins.
    # What a basecaller writes in the calibration column when a read did not
    # align to a control genome. Albacore: filtered_out, no_match. Guppy 2.2
    # onwards: *, wrong_length. An empty field counts too.
    CALIBRATION_SENTINELS = frozenset(
        ["filtered_out", "no_match", "*", "wrong_length", "", "-1", "nan"])

    RUN_METADATA_COLUMNS = (
        ("Run started", ("run_start_time", "acquisition_start_time",
                         "exp_start_time", "protocol_start_time")),
        ("Sample", ("sample_id", "sampleid", "sample")),
        ("Experiment", ("experiment_id", "experiment_name", "protocol_group_id")),
        ("Flow cell ID", ("flow_cell_id", "flowcell_id")),
        ("Flow cell type", ("flow_cell_product_code", "flowcell_type")),
        ("Device", ("device_id", "device", "hostname")),
        ("Device type", ("device_type", "sequencer_position_type")),
        ("Sequencing kit", ("sequencing_kit",)),
        ("Barcoding kit", ("barcode_kit", "barcode_arrangement_kit")),
        ("Basecalling model", ("dorado_model", "basecall_model",
                               "model_version_id", "basecaller_model")),
        ("Acquisition software", ("software", "minknow_version")),
        ("Protocol", ("protocol_name",)),
        ("Protocol run ID", ("protocol_run_id",)),
    )

    def _collect_run_metadata(self, df):
        """Record the run level columns before the unused ones are dropped

        A summary carries more about the run than pycoQC plots: the flow cell,
        the device, the kit, the basecalling model. Those columns are
        discarded when the frame is reduced to what the plots need, so they
        are collected here for the report to show.

        A column counts as run level only if it holds a handful of distinct
        values at most; anything more varies per read and is not metadata.
        """
        metadata = OrderedDict()
        for label, candidates in self.RUN_METADATA_COLUMNS:
            for column in candidates:
                if column not in df:
                    continue
                values = df[column].dropna().astype(str)
                values = values[values.str.strip() != ""]
                unique = values.unique()
                if len(unique) == 0 or len(unique) > 4:
                    continue
                metadata[label] = ", ".join(sorted(unique))
                break
        return metadata

    def _parse_barcode(self):
        """"""
        df = pd.DataFrame()

        if self.barcode_files_list:
            self.logger.debug("\tParse barcode files")
            df = merge_files_to_df(self.barcode_files_list, self.logger)

        # Check presence of barcode details
            if "read_id" in df and "barcode_arrangement" in df:
                self.logger.debug("\t\tFound valid Guppy barcode file")
                df = df.rename(columns={"barcode_arrangement": "barcode"})

            elif "read_ID" in df and "barcode_call" in df:
                self.logger.debug("\t\tFound valid Deepbinner barcode file")
                df = df.rename(columns={"read_ID": "read_id", "barcode_call": "barcode"})

            df = df[["read_id", "barcode"]]
            # Deepbinner writes barcodes as bare numbers, so pandas types the
            # column as int, or as float once the merge introduces a missing
            # value for a read the file does not mention. Barcode 6 then
            # arrives as 6, "6" or 6.0 depending on the file and the chunk it
            # was read in, which splits one barcode into several in the
            # report, names its output file sequencing_summary_6.0.txt, and
            # makes sorting the labels raise. A barcode is a name, not a
            # quantity, so it is read as one.
            df["barcode"] = df["barcode"].astype(str).str.strip()
            # Overlapping barcode files repeat read ids, and a left merge on
            # a duplicated key multiplies the read rather than failing, so
            # every count came out slightly high.
            duplicated = df["read_id"].duplicated().sum()
            if duplicated:
                self.logger.info(
                    "\t\t{:,} duplicated read ids in the barcode file(s) "
                    "ignored".format(duplicated))
                df = df.drop_duplicates(subset="read_id", keep="first")
            # Assign the result back: an inplace call on a single column
            # operates on a temporary copy under copy-on-write and silently
            # leaves the frame unchanged, so "none" stayed a barcode name.
            df['barcode'] = df['barcode'].replace("none", "unclassified")

            n = len(df[df['barcode'] != "unclassified"])
            self.logger.debug("\t\t{:,} reads with barcodes assigned".format(n))
            self.counter["Reads with barcodes"] = n

        return df

    def _parse_bam(self):
        """"""
        if not self.bam_file_list:
            return pd.DataFrame(), pd.DataFrame(), OrderedDict()

        # Init collections
        ref_len_dict = OrderedDict()
        alignments_dict = Counter()
        read_dict = OrderedDict()

        for bam_fn in self.bam_file_list:
            with ps.AlignmentFile(bam_fn, "rb") as bam:

                # Save reference lengths information
                for ref_id, ref_len in zip(bam.references, bam.lengths):
                    if ref_id not in ref_len_dict:
                        ref_len_dict[ref_id] = ref_len

                # Parse reads
                for read in bam:
                    if read.is_unmapped:
                        alignments_dict["Unmapped"] += 1
                    elif read.is_secondary:
                        alignments_dict["Secondary"] += 1
                    elif read.is_supplementary:
                        alignments_dict["Suplementary"] += 1
                    elif read.query_name in read_dict:
                        alignments_dict["Duplicated"] += 1
                    else:
                        alignments_dict["Primary"] += 1
                        read_dict[read.query_name] = self._get_read_stats(read)

        # Convert alignments_dict to df
        if alignments_dict:
            alignments_df = pd.DataFrame.from_dict(alignments_dict, orient="index")
            alignments_df.reset_index(inplace=True)
            alignments_df.columns = ["Alignments", "Counts"]
            alignments_df["Percents"] = (alignments_df["Counts"] / alignments_df["Counts"].sum() * 100).round(2)
        else:
            alignments_df = pd.DataFrame()

        # Convert read_dict to df
        if read_dict:
            read_df = pd.DataFrame.from_dict(read_dict, orient="index")
            read_df.index.name = "read_id"
            read_df.reset_index(inplace=True)
        else:
            read_df = pd.DataFrame()

        return read_df, alignments_df, ref_len_dict

    def _merge_reads_df(self, summary_reads_df, barcode_reads_df, bam_reads_df):
        """"""
        df = summary_reads_df

        # Merge df and fill in missing barcode values
        if not barcode_reads_df.empty:
            # A summary written with barcoding already has a barcode column,
            # and merging another one left barcode_x and barcode_y rather
            # than barcode, so the next line raised KeyError. The separate
            # file is the more specific source, so it wins. Without the
            # renaming pass that cleanup does, the summary's column is still
            # called barcode_arrangement, and leaving it in place gave the
            # caller two barcode columns as soon as it renamed that one,
            # which is what Barcode_split does.
            for col in ("barcode", "barcode_arrangement"):
                if col in df:
                    self.logger.debug(
                        "\tBarcodes in the summary are replaced by the barcode file")
                    df = df.drop(columns=col)
            df = pd.merge(df, barcode_reads_df, on="read_id", how="left")
            # Same here: reads absent from the barcode file kept a missing
            # barcode instead of being marked unclassified.
            df['barcode'] = df['barcode'].fillna('unclassified')

        # Merge df and fill in missing barcode values
        if not bam_reads_df.empty:
            df = pd.merge(df, bam_reads_df, on="read_id", how="left")

        return df

    def _clean_reads_df(self, df):
        """"""
        # A converter emits a column even when it could not fill it, so an
        # entirely empty optional column means the information is absent
        # rather than that every read should be discarded.
        for col in ("run_id", "channel", "start_time", "barcode", "%GC"):
            if col in df and df[col].isna().all():
                self.logger.info("\tNo {} information available".format(col))
                df = df.drop(columns=col)

        # A partly filled barcode column is normal: only some of a run may
        # have been demultiplexed, and the converters leave the field empty
        # for a read with no barcode tag. Those blanks have to be named,
        # because sorting a mixture of strings and nan raises, which took
        # the whole report down, while the plots that did not sort quietly
        # left those reads out. The separate barcode file was already
        # handled this way.
        # Same reasoning as the barcode file: a summary whose barcodes are
        # numbers must not be typed as numbers.
        if "barcode" in df:
            df["barcode"] = df["barcode"].astype("object").where(
                df["barcode"].isna(), df["barcode"].astype(str).str.strip())

        if "barcode" in df and df["barcode"].isna().any():
            missing = int(df["barcode"].isna().sum())
            self.logger.info(
                "\t{:,} reads without a barcode marked unclassified".format(missing))
            df["barcode"] = df["barcode"].fillna("unclassified")

        # Drop reads that cannot be reported on at all. A read needs an id,
        # a length and a quality score; everything else only decides which
        # plots it can appear in. Requiring the optional columns as well
        # discarded reads that had all three: a BAM where some records carry
        # no ch or st tag lost those reads from the read count, the yield and
        # the N50, which are exactly the numbers people quote.
        self.logger.info("\tDiscarding lines containing NA values")
        l = len(df)
        subset = [c for c in ("read_id", "read_len", "mean_qscore") if c in df]
        df = df.dropna(subset=subset)
        n = l-len(df)
        self.logger.info("\t\t{:,} reads discarded".format(n))
        self.counter["Reads with NA values discarded"] = n
        self._require_reads(df, "discarding reads with missing values")

        # Say which reads will be missing from which plots, since that is no
        # longer visible as a drop in the read count.
        for col, plots in (("start_time", "the over time plots"),
                           ("channel", "the channel activity plot"),
                           ("run_id", "the per run ordering"),
                           ("%GC", "the %GC plots")):
            if col in df and df[col].isna().any():
                self.logger.info(
                    "\t\t{:,} reads have no {} and are left out of {}".format(
                        int(df[col].isna().sum()), col, plots))

        # Filter out zero length reads
        self.logger.info("\tFiltering out zero length reads")
        l = len(df)
        df = df[(df["read_len"] > 0)]
        n = l-len(df)
        self.logger.info("\t\t{:,} reads discarded".format(n))
        self.counter["Zero length reads discarded"] = n
        self._require_reads(df, "discarding zero length reads")

        # Filter out reads with duplicated read_id
        if self.filter_duplicated:
            self.logger.info("\tFiltering out duplicated reads")
            l = len(df)
            df = df[~df.duplicated(subset="read_id", keep='first')]
            n = l-len(df)
            self.logger.info("\t\t{:,} reads discarded".format(n))
            self.counter["Duplicated reads discarded"] = n
            self._require_reads(df, "discarding duplicated reads")

        # Filter out calibration strand reads, where the basecaller recorded
        # which control genome each read aligned to. A read that aligned to
        # one is a control strand; the rest of the column is sentinels saying
        # why no alignment was recorded, and those differ by basecaller:
        # Albacore writes filtered_out and no_match, Guppy 2.2 writes * and
        # wrong_length. Keeping a list of the sentinels and discarding
        # everything else was the wrong way round, because an unrecognised
        # sentinel then looks like a genome name: run the Guppy file through
        # it and 45,541 of 50,000 reads are thrown away as controls.
        if self.filter_calibration and "calibration" in df:
            self.logger.info("\tFiltering out calibration strand reads")
            l = len(df)
            values = df["calibration"].astype(str).str.strip()
            is_control = ~values.isin(self.CALIBRATION_SENTINELS) & df["calibration"].notna()
            n = int(is_control.sum())

            # A control is a spike-in, never the bulk of a run, so a filter
            # that wants to drop most of the reads has not understood the
            # column. Say so rather than publish a report missing them.
            if n > len(df) / 2:
                unknown = values[is_control].value_counts().head(5)
                raise pycoQCError(
                    "Calibration filtering would discard {:,} of {:,} reads. The "
                    "values {} are not recognised, and are more likely to be "
                    "markers this version of pycoQC does not know than genuine "
                    "control strands. Rerun without --filter_calibration, and "
                    "please report these values as an issue.".format(
                        n, len(df), ", ".join(repr(v) for v in unknown.index)))

            df = df[~is_control]
            self.logger.info("\t\t{:,} reads discarded".format(n))
            self.counter["Calibration reads discarded"] = n
            self._require_reads(df, "discarding calibration strands")

        # Ordering runs in time needs both columns; without them there is
        # nothing to order and the reads are left as they are.
        if "run_id" not in df or "start_time" not in df:
            self.logger.info("\tSkipping run ordering, no run_id or start_time")
            return self._finalise_reads_df(df)

        # Filter and reorder based on runid_list list if passed by user
        if self.runid_list:
            self.logger.info("\tSelecting run_ids passed by user")
            l = len(df)
            df = df[(df["run_id"].isin(self.runid_list))]
            n = l - len(df)
            self.logger.debug("\t\t{:,} reads discarded".format(n))
            self.counter["Excluded runid reads discarded"] = n
            self._require_reads(df, "selecting the requested run ids")
            runid_list = self.runid_list

        # Else sort the runids by output per time assuming that the throughput decreases over time
        else:
            self.logger.info("\tSorting run IDs by decreasing throughput")
            d = {}
            for run_id, sdf in df.groupby("run_id"):
                # A run whose reads all carry the same timestamp spans no
                # time, so throughput is undefined rather than infinite. Rank
                # it last instead of dividing by zero.
                times = sdf["start_time"].dropna()
                span = float(times.max() - times.min()) if len(times) else 0.0
                d[run_id] = len(sdf) / span if span else 0.0
            runid_list = [i for i, j in sorted(d.items(), key=lambda t: t[1], reverse=True)]
            self.logger.info("\t\tRun-id order {}".format(runid_list))

        # Modify start time per run ids to order them following the runid_list
        self.logger.info("\tReordering runids")
        increment_time = 0
        runid_start = OrderedDict()
        for runid in runid_list:
            self.logger.info("\t\tProcessing reads with Run_ID {} / time offset: {}".format(
                runid, increment_time))
            selected = df["run_id"] == runid
            if not selected.any():
                # max() of nothing is NaN, and adding it to the offset made
                # every later run's start_time NaN, silently emptying the
                # time plots instead of reporting the unknown id.
                self.logger.info(
                    "\t\tNo reads found for Run_ID {}".format(runid))
                continue
            max_val = df['start_time'][selected].max()
            df.loc[selected, 'start_time'] += increment_time
            runid_start[runid] = increment_time
            increment_time += max_val+1
        df = df.sort_values("start_time")

        return self._finalise_reads_df(df)

    def _finalise_reads_df(self, df):
        """Barcode cleanup, typing and indexing, shared by every input

        Reached either after the runs have been ordered in time, or directly
        when there is no run or timing information to order by.
        """
        #  Unset low frequency barcodes
        if "barcode" in df and self.min_barcode_percent:
            self.logger.info("\tCleaning up low frequency barcodes")
            l = (df["barcode"] == "unclassified").sum()
            barcode_counts = df["barcode"][df["barcode"] != "unclassified"].value_counts()
            cutoff = int(barcode_counts.sum() * self.min_barcode_percent/100)
            low_barcode = barcode_counts[barcode_counts < cutoff].index
            df.loc[df["barcode"].isin(low_barcode), "barcode"] = "unclassified"
            n= int((df["barcode"] == "unclassified").sum() - l)
            self.logger.info("\t\t{:,} reads with low frequency barcode unset".format(n))
            self.counter["Reads with low frequency barcode unset"] = n

        # Cast values to required types. A column that is missing for some
        # reads cannot hold a plain integer, so the nullable type is used
        # instead of dropping those reads for the sake of the dtype.
        self.logger.info("\tCast value to appropriate type")
        dtypes = {"channel": "uint16", "start_time": "float32",
                  "read_len": "uint32", "mean_qscore": "float32"}
        nullable = {"uint16": "UInt16", "uint32": "UInt32"}
        cast = {}
        for col, dtype in dtypes.items():
            if col not in df:
                continue
            if dtype in nullable and df[col].isna().any():
                dtype = nullable[dtype]
            cast[col] = dtype
        df = df.astype(cast)

        # Reindex final df
        self.logger.info("\tReindexing dataframe by read_ids")
        df = df.reset_index(drop=True)
        df = df.set_index("read_id")
        self.logger.info("\t\t{:,} Final valid reads".format(len(df)))

        # Save final df
        self.counter["Valid reads"] = len(df)
        if len(df) < 500:
            self.logger.warning("WARNING: Low number of reads found. This is likely to lead to errors when trying to generate plots")

        return df

    def _get_read_stats(self, read):
        """"""
        d = OrderedDict()

        # Extract general stats
        d["ref_id"] = read.reference_name
        d["ref_start"] = read.reference_start
        d["ref_end"] = read.reference_end
        d["align_len"] = read.query_alignment_length
        d["mapq"] = read.mapping_quality

        # Extract indel and soft_clip from cigar
        c_stat = read.get_cigar_stats()[0]
        d["insertion"] = c_stat[1]
        d["deletion"] = c_stat[2]
        d["soft_clip"] = c_stat[4]

        # Compute alignment score from NM field if available
        if read.has_tag("NM"):
            edit_dist = read.get_tag("NM")
            d["mismatch"] = edit_dist - (d["deletion"] + d["insertion"])
            try:
                d["identity_freq"] = (d["align_len"] - edit_dist) / d["align_len"]
            except ZeroDivisionError:
                d["identity_freq"] = 0

        # If not NM try to compute score from MD field
        elif read.has_tag("MD"):
            md_err = 0
            for i in read.get_tag("MD"):
                if i in ["A", "T", "C", "G", "a", "t", "c", "g"]:
                    md_err += 1
            d["mismatch"] = md_err - d["deletion"]
            edit_dist = d["mismatch"] + d["insertion"] + d["deletion"]
            try:
                d["identity_freq"] = (d["align_len"] - edit_dist) / d["align_len"]
            except ZeroDivisionError:
                d["identity_freq"] = 0

        return d

    def _select_df_columns(self, df, required_colnames, optional_colnames):
        """"""
        col_found = []
        # Verify the presence of the columns required for pycoQC
        for col in required_colnames:
            if col in df:
                col_found.append(col)
            elif col in ("read_len", "mean_qscore"):
                # These two only exist once the reads have been basecalled.
                # A summary built from POD5, or from a FAST5 holding signal
                # only, has neither, and naming the internal column alone
                # left no clue what to do about it.
                raise pycoQCError(
                    "Column {} not found in the provided sequence_summary "
                    "file. Read length and quality only exist once the reads "
                    "are basecalled, and a summary built from POD5 or from "
                    "raw FAST5 has neither. Basecall the run first, then "
                    "build the summary with Bam_to_seq_summary or "
                    "Fastq_to_seq_summary.".format(col))
            else:
                raise pycoQCError("Column {} not found in the provided sequence_summary file".format(col))
        for col in optional_colnames:
            if col in df:
                col_found.append(col)

        return df[col_found]
