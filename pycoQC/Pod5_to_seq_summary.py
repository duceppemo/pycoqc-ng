# Standard library imports
import os

# Third party imports
import pod5 as p5

# Local imports
from pycoQC._pipeline import ConverterPipeline
from pycoQC.common import (
    path_has_token)



#~~~~~~~~~~~~~~CLASS~~~~~~~~~~~~~~#
class Pod5_to_seq_summary(ConverterPipeline):
    """
    Create a summary file akin the one generated by Dorado from a directory containing
    multiple pod5 files. The script will attempt to extract all the required fields but will not
    raise an error if not found.
    """
    kind = "pod5"
    extensions = ("pod5",)
    # A directory can hold a run and a copy of it.
    unique_read_ids = True

    def __init__(self,
                 pod5_dir: str,
                 seq_summary_fn: str,
                 max_pod5: int = 0,
                 threads: int = 4,
                 basecall_id: int = 0,
                 verbose_level: int = 0,
                 include_path: bool = False):
        """
        * pod5_dir
            Directory containing pod5 files. Can contain multiple subdirectories
        * seq_summary_fn
            path of the summary sequencing file where to write the data extracted from the pod5 files
        * max_pod5
            Maximum number of file to try to parse. 0 to deactivate
        * threads
            Total number of threads to use. 1 thread is used for the reader and 1 for the writer. Minimum 3 (default = 4)
        * basecall_id
            id of the basecalling group. By default, leave to 0, but if you perform multiple basecalling on the same pod5 files,
            this can be used to indicate the corresponding group (1, 2 ...)
        * include_path
            If True the absolute path to the corresponding file is added in an extra column
        * verbose_level
            Level of verbosity, from 2 (Chatty) to 0 (Nothing)
        """
        self._configure(pod5_dir, seq_summary_fn, max_pod5, threads,
                        basecall_id, include_path, verbose_level)

        self._run()

    #~~~~~~~~~~~~~~PIPELINE STAGES~~~~~~~~~~~~~~#
    def _records(self, pod5_file, counts):
        """One dict per read of a pod5 file, created from fast5 or by MinKNOW."""
        with p5.Reader(pod5_file) as reader:
            for read in reader.reads():
                run_id = read.run_info.acquisition_id
                read_id = str(read.read_id)
                channel = read.pore.channel

                # Compute the start_time in seconds
                sample_rate = read.run_info.sample_rate
                start = read.start_sample
                start_time = int(start / sample_rate)

                # Computer duration
                num_sample = read.num_samples
                duration = num_sample / sample_rate

                sample_id = read.run_info.sample_id
                flowcell_id = read.run_info.flow_cell_id
                run_start = read.run_info.acquisition_start_time
                flowcell_type = read.run_info.flow_cell_product_code
                sequencing_kit = read.run_info.sequencing_kit
                device = read.run_info.sequencer_position
                software = read.run_info.software
                read_number = read.read_number

                # Info that might not be present
                file_name = os.path.basename(pod5_file)
                field_list = file_name.split('_')

                # Barcode
                if 'barcode' in file_name:
                    barcode = [i for i in field_list if 'barcode' in i][0]
                elif 'unclassified' in file_name:
                    barcode = 'unclassified'
                else:
                    # A run that was never demultiplexed has no barcode.
                    # Writing "skip" here invented one, and a report then
                    # showed every read assigned to a barcode called skip,
                    # which is also a real MinKNOW file name token.
                    barcode = ''

                # Flag, matched on whole words so a path such as
                # /data/failover/pod5_pass is not read as failing. pass is
                # still tested first, so it wins if a name holds both.
                if path_has_token(file_name, 'pass'):
                    flag = 'TRUE'
                elif path_has_token(file_name, 'fail'):
                    flag = 'FALSE'
                elif path_has_token(file_name, 'skip'):
                    flag = 'FALSE'
                else:
                    flag = 'TRUE'  # For pod5 converted from fast5?

                d = {"read_id": read_id,
                     "run_id": run_id,
                     "channel": channel,
                     "start_time": start_time,
                     "duration": duration,
                     "sample_id": sample_id,
                     "flowcell_id": flowcell_id,
                     "read_number": read_number,
                     "barcode_arrangement": barcode,
                     "passes_filtering": flag,
                     # Why the read ended, and which of the channel's pores
                     # it came from.
                     "end_reason": read.end_reason.name,
                     "mux": read.pore.well,
                     # Run level fields, carried so the report can describe
                     # the run rather than only the reads.
                     "run_start_time": run_start,
                     "flow_cell_product_code": flowcell_type,
                     "sequencing_kit": sequencing_kit,
                     "device_id": device,
                     "software": software,
                     "path": os.path.abspath(pod5_file),
                     }
                yield d

    def _finalise(self, df, notes):
        # --include_path: the path was stored and never read, so the option
        # did nothing.
        if not self.include_path:
            df = df.drop(columns="path", errors="ignore")

        # A POD5 file holds raw signal, not basecalls, so there is no read
        # length and no quality score to report. Earlier versions filled those
        # two columns with values drawn from np.random.normal to get past
        # pycoQC's requirement that they be present, which meant every length
        # and quality figure in a report built from POD5 was invented, down to
        # negative read lengths. Only the fields POD5 actually carries are
        # written now.
        notes.append(
            "POD5 holds raw signal only, so this summary has no read length "
            "or quality columns. pycoQC will report on the run itself: how "
            "many reads, from which pores, when, how long each one took and "
            "under which barcode. For read lengths, quality scores and yield, "
            "basecall first and use Bam_to_seq_summary or "
            "Fastq_to_seq_summary.")
        return df
