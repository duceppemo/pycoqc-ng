def _report_errors(main):
    """Turn a pycoQCError into a one line message and exit status 1.

    pycoQCError is what pycoQC raises for a problem with the input or the
    options, which the person running the command can fix, and a traceback
    buried the sentence that said how. Anything else is a bug and keeps its
    traceback.
    """
    @functools.wraps(main)
    def wrapper(args=None):
        try:
            return main(args)
        except pycoQCError as E:
            sys.stderr.write("ERROR: {}\n".format(E))
            sys.exit(1)
    return wrapper


#~~~~~~~~~~~~~~pycoQC CLI ENTRY POINT~~~~~~~~~~~~~~#
@_report_errors
def main_pycoQC(args=None):
    if args is None:
        args = sys.argv[1:]

    # Define parser object
    parser = argparse.ArgumentParser(
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description=textwrap.dedent("""
            pycoQC computes metrics and generates interactive QC plots from the sequencing summary
            report generated by Oxford Nanopore technologies basecallers\n
            * Minimal usage
                pycoQC -f sequencing_summary.txt -o pycoQC_output.html
            * Including Guppy barcoding file + html output + json output
                pycoQC -f sequencing_summary.txt -b barcoding_sequencing.txt -o pycoQC_output.html -j pycoQC_output.json
            * Including Bam file + html output
                pycoQC -f sequencing_summary.txt -a alignment.bam -o pycoQC_output.html"""))
    parser.add_argument('--version', action='version', version="{} v{}".format(package_name, package_version))

    # Define arguments
    parser_io = parser.add_argument_group('Input/output options')
    parser_io.add_argument("--summary_file", "-f", default=[], nargs='*',
        help=textwrap.dedent("Path to a sequencing_summary generated by Albacore 1.0.0 +(read_fast5_basecaller.py) / "
                             "Guppy 2.1.3+(guppy_basecaller) / Dorado 0.4.1+(dorado basecaller). One can also pass "
                             "multiple space separated file paths or a UNIX style regex matching multiple "
                             "files(Required)"))
    parser_io.add_argument("--barcode_file", "-b", default=[], nargs='*',
                           help=textwrap.dedent("Path to the barcode_file generated by Guppy 2.1.3+(guppy_barcoder) "
                                                "or Deepbinner 0.2.0+. This is not a required file. One can also pass "
                                                "multiple space separated file paths or a UNIX style regex matching "
                                                "multiple files(optional)"))
    parser_io.add_argument("--bam_file", "-a", default=[], nargs='*',
                           help=textwrap.dedent("Path to a Bam file corresponding to reads in the summary_file. "
                                                "Preferably aligned with Minimap2. One can also pass multiple space "
                                                "separated file paths or a UNIX style regex matching multiple "
                                                "files(optional)"))
    parser_io.add_argument("--html_outfile", "-o", default="", type=str,
                           help="Path to an output html file report(required if json_outfile not given)")
    parser_io.add_argument("--json_outfile", "-j", default="", type=str,
                           help="Path to an output json file report(required if html_outfile not given)")
    parser_io.add_argument("--pdf_outfile", "-p", default="", type=str,
                           help="Path to an output pdf file report. Static and much smaller than the "
                                "html report. Needs the pdf extra: pip install 'pycoqc-ng[pdf]'(optional)")
    parser_filt = parser.add_argument_group('Filtering options')
    parser_filt.add_argument("--min_pass_qual", default=7, type=float,
                             help="Minimum quality to consider a read as 'pass'(default: %(default)s)")
    parser_filt.add_argument("--min_pass_len", default=0, type=int,
                             help="Minimum read length to consider a read as 'pass'(default: %(default)s)")
    parser_filt.add_argument("--filter_calibration", default=False, action='store_true',
                             help="If given, reads flagged as calibration strand by the basecaller are "
                                  "removed(default: %(default)s)")
    parser_filt.add_argument("--filter_duplicated", default=False, action='store_true',
                             help=textwrap.dedent("If given, duplicated read_ids are removed but the first "
                                                  "occurrence is kept (Guppy sometimes outputs the same read multiple "
                                                  "times)(default: %(default)s)"))
    parser_filt.add_argument("--min_barcode_percent", default=0.1, type=float,
                             help="Minimal percent of total reads to retain barcode label. If below, the barcode value "
                                  "is set as `unclassified`(default: %(default)s)")
    # The Python API has always taken this, and so did the original pycoQC
    # command line; this one had lost it.
    parser_filt.add_argument("--runid_list", default=[], nargs='*',
                             help=textwrap.dedent("Select only specific runids to be analysed. Can also be used to "
                                                  "force pycoQC to order the runids for temporal plots, if the "
                                                  "sequencing_summary file contain several successive runs. By default "
                                                  "pycoQC analyses all the runids in the file and orders them by "
                                                  "decreasing throughput(default: all runids)"))
    parser_html = parser.add_argument_group('HTML report options')
    parser_html.add_argument("--report_title", default="PycoQC report", type=str,
                             help="Title to use in the html report(default: %(default)s)")
    parser_html.add_argument("--template_file", type=str, default="",
                             help="Jinja2 html template for the html report(default: %(default)s)")
    parser_html.add_argument("--config_file", type=str, default="",
                             help=textwrap.dedent("Path to a JSON configuration file for the html report. If not "
                                                  "provided, looks for it in ~/.pycoQC and ~/.config/pycoQC/config. If "
                                                  "it's still not found, falls back to default parameters. The first "
                                                  "level keys are the names of the plots to be included. The second "
                                                  "level keys are the parameters to pass to each plotting "
                                                  "function(default: %(default)s))"))
    parser_html.add_argument("--skip_coverage_plot", default=False, action='store_true',
                             help="Skip the coverage plot in HTML report. Useful when using a reference file containing"
                                  " many sequences, i.e. transcriptome(default: %(default)s)")
    parser_other = parser.add_argument_group('Other options')
    parser_other.add_argument("--sample", default=100000, type=int,
                              help=textwrap.dedent("If not None a n number of reads will be randomly selected instead "
                                                   "of the entire dataset for plotting function (deterministic "
                                                   "sampling)(default: %(default)s)"))
    parser_other.add_argument("--default_config", "-d", action='store_true',
                              help="Print default configuration file. Can be used to generate a template JSON "
                                   "file(default: %(default)s)")
    parser_verbosity = parser.add_mutually_exclusive_group()
    parser_verbosity.add_argument("-v", "--verbose", action="store_true", default=False,
                                  help="Increase verbosity")
    parser_verbosity.add_argument("-q", "--quiet", action="store_true", default=False,
                                  help="Reduce verbosity")

    # Try to parse arguments
    args = parser.parse_args(args)

    # Set logging level
    logger = get_logger(name=__name__, verbose=args.verbose, quiet=args.quiet)

    # Print the default config parameters and exit
    if args.default_config:
        config_json = files("pycoQC").joinpath("templates/pycoQC_config.json")
        sys.stdout.write(config_json.read_text())
        sys.exit(0)

    elif not args.summary_file:
        logger.warning("ERROR: `--summary_file` is a required argument")
        parser.print_help()
        sys.exit(2)

    elif not args.html_outfile and not args.json_outfile and not args.pdf_outfile:
        logger.warning("ERROR: At least one output file required `--html_outfile`, `--json_outfile` or `--pdf_outfile`")
        parser.print_help()
        sys.exit(2)

    # Run pycoQC
    pycoQC(
        summary_file=args.summary_file,
        barcode_file=args.barcode_file,
        bam_file=args.bam_file,
        runid_list=args.runid_list,
        filter_calibration=args.filter_calibration,
        filter_duplicated=args.filter_duplicated,
        min_barcode_percent=args.min_barcode_percent,
        min_pass_qual=args.min_pass_qual,
        min_pass_len=args.min_pass_len,
        sample=args.sample,
        html_outfile=args.html_outfile,
        report_title=args.report_title,
        config_file=args.config_file,
        skip_coverage_plot=args.skip_coverage_plot,
        template_file=args.template_file,
        json_outfile=args.json_outfile,
        pdf_outfile=args.pdf_outfile,
        verbose=args.verbose,
        quiet=args.quiet)


#~~~~~~~~~~~~~~CONVERTER CLI ENTRY POINTS~~~~~~~~~~~~~~#
def _run_converter(args, converter, kind, fields_help=None):
    """Parse a converter's command line and run it.

    The four converters take the same options, so the parser is built once
    here. The --fields default is read from the converter itself: two copies
    of each list, one here and one in the class, had already drifted apart
    once, and a summary built from the command line lacked the columns the
    same call from Python wrote.

    * kind
        The input format, which names the --<kind>_dir and --max_<kind>
        options and the converter's own arguments.
    * fields_help
        Help for --fields, for a converter that has the option.
    """
    if args is None:
        args = sys.argv[1:]

    parser = argparse.ArgumentParser(
        description="{} generate a sequencing summary like file from a directory containing "
                    "{} files".format(converter.__name__, kind))
    parser.add_argument('--version', '-v', action='version', version="{} v{}".format(
        package_name, package_version))
    parser.add_argument("--{}_dir".format(kind), "-f", required=True, type=str,
                        help="Directory containing {} files. Can contain multiple subdirectories".format(kind))
    parser.add_argument("--seq_summary_fn", "-s", required=True, type=str,
                        help="Path of the summary sequencing file where to write the data extracted from the "
                             "{} files".format(kind))
    parser.add_argument("--max_{}".format(kind), type=int, default=0,
                        help="Maximum number of file to try to parse. 0 to deactivate(default: %(default)s)")
    parser.add_argument("--threads", "-t", type=int, default=4,
                        help="Total number of threads to use. 1 thread is used for the reader and 1 for the writer. "
                             "Minimum 3(default: %(default)s)")
    if kind == "fast5":
        basecall_help = ("ID of the basecalling group. By default leave to 0, but if you perform multiple "
                         "basecalling on the same fast5 files, this can be used to indicate the corresponding "
                         "group(1, 2 ...)(default: %(default)s)")
    else:
        basecall_help = ("Selects one of several basecalling groups inside a FAST5. It has no meaning for {} "
                         "input and is ignored. Kept so existing command lines keep working"
                         "(default: %(default)s)".format(kind))
    parser.add_argument("--basecall_id", type=int, default=0, help=basecall_help)
    if fields_help:
        default = inspect.signature(converter).parameters["fields"].default
        if default is not None:
            default = list(default)
            fields_help += "(default: %(default)s)"
        parser.add_argument("--fields", type=str, nargs="+", default=default,
                            help=fields_help)
    parser.add_argument("--include_path", action='store_true', default=False,
                        help="If given, the absolute path to the corresponding file is added in an extra "
                             "column(default: %(default)s)")
    parser.add_argument("--verbose_level", type=int, default=0,
                        help="Level of verbosity, from 2(Chatty) to 0(Nothing)(default: %(default)s)")

    args = vars(parser.parse_args(args))
    converter(**args)


@_report_errors
def main_Fast5_to_seq_summary(args=None):
    _run_converter(args, Fast5_to_seq_summary, "fast5", fields_help=(
        "List of field names corresponding to attributes to try to fetch from the fast5 files"))


@_report_errors
def main_Fastq_to_seq_summary(args=None):
    _run_converter(args, Fastq_to_seq_summary, "fastq", fields_help=(
        "List of field names corresponding to attributes to try to fetch from the fastq headers"))


@_report_errors
def main_Pod5_to_seq_summary(args=None):
    _run_converter(args, Pod5_to_seq_summary, "pod5")


@_report_errors
def main_Bam_to_seq_summary(args=None):
    _run_converter(args, Bam_to_seq_summary, "bam", fields_help=(
        "Columns to keep in the summary. By default every field the bam files carry is written"))


#~~~~~~~~~~~~~~Barcode_split CLI ENTRY POINT~~~~~~~~~~~~~~#
@_report_errors
def main_Barcode_split(args=None):
    if args is None:
        args = sys.argv[1:]

    # Define parser object
    parser = argparse.ArgumentParser(
        description ="Barcode_split is a simple tool to split sequencing summary report in per barcodes")
    parser.add_argument('--version', action='version',
                        version="{} v{}".format(package_name, package_version))
    # Define arguments
    parser.add_argument("--summary_file", "-f", required=True, nargs='*',
                        help=textwrap.dedent("Path to a sequencing_summary generated by "
                                             "Albacore 1.0.0 +(read_fast5_basecaller.py) / "
                                             "Guppy 2.1.3+(guppy_basecaller) / Dorado 0.4.1+(dorado basecaller). One "
                                             "can also pass multiple space separated file paths or a UNIX style regex "
                                             "matching multiple files"))
    parser.add_argument("--barcode_file", "-b", default=[], nargs='*',
                        help=textwrap.dedent("Path to the barcode_file generated by Guppy 2.1.3+(guppy_barcoder) or "
                                             "Deepbinner 0.2.0+. One can also pass multiple space separated file paths "
                                             "or a UNIX style regex matching multiple files"))
    parser.add_argument("--output_dir", "-o", type=str, default="",
                        help="Folder where to output split barcode data(default: current dir)")
    parser.add_argument("--output_unclassified", "-u", action='store_true', default=False,
                        help="If given, unclassified barcodes are also written in a file. By default they are skipped")
    parser.add_argument("--min_barcode_percent", "-p", default=0.1, type=float,
                        help="Minimal percent of total reads to retain barcode label. If below, the barcode value is "
                             "set as `unclassified`(default: %(default)s)")
    parser_verbosity = parser.add_mutually_exclusive_group()
    parser_verbosity.add_argument("-v", "--verbose", action="store_true", default=False,
                                  help="Increase verbosity")
    parser_verbosity.add_argument("-q", "--quiet", action="store_true", default=False,
                                  help="Reduce verbosity")

    # Try to parse arguments
    args = parser.parse_args(args)

    # Run main function
    barcode_split(
        summary_file=args.summary_file,
        barcode_file=args.barcode_file,
        output_dir=args.output_dir,
        output_unclassified=args.output_unclassified,
        min_barcode_percent=args.min_barcode_percent,
        verbose=args.verbose,
        quiet=args.quiet)


#~~~~~~~~~~~~~~MODULE ENTRY POINT~~~~~~~~~~~~~~#
if __name__ == "__main__":
    # Makes `python -m pycoQC ...` equivalent to the pycoQC console script.
    main_pycoQC()
