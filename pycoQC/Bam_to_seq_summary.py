#~~~~~~~~~~~~~~IMPORTS~~~~~~~~~~~~~~#
# Standard library imports
import logging
import os
from concurrent.futures import ThreadPoolExecutor

# Third party imports
import pandas as pd
from tqdm import tqdm
import pysam

# Local imports
from pycoQC.common import (
    mean_qscore,
    path_has_token,
    parse_timestamp,
    pycoQCError,
    recursive_file_gen,
    elapsed_seconds_per_run)


# Logger setup
logging.basicConfig(level=logging.INFO, format='%(message)s')
logger = logging.getLogger(__name__)
logLevel_dict = {2: logging.DEBUG, 1: logging.INFO, 0: logging.WARNING}


#~~~~~~~~~~~~~~CLASS~~~~~~~~~~~~~~#
class Bam_to_seq_summary():
    """
    Create a summary file akin the one generated by Albacore or Guppy from a directory containing
    multiple bam files. The script will attempt to extract all the required fields but will not
    raise an error if not found.
    """
    
    def __init__(self,
                 bam_dir: str,
                 seq_summary_fn: str,
                 max_bam: int = 0,
                 threads: int = 4,
                 basecall_id: int = 0,
                 verbose_level: int = 0,
                 include_path: bool = False,
                 # Everything the BAM carries, by default. The old default
                 # named a subset which, now that it is honoured, would drop
                 # the flow cell, the device and the run start time that the
                 # report describes the run with, and would name a
                 # calibration column that no BAM has.
                 fields: list = None):
        """
        * bam_dir
            Directory containing bamfiles. Can contain multiple subdirectories
        * seq_summary_fn
            path of the summary sequencing file where to write the data extracted from the bam files
        * max_bam
            Maximum number of file to try to parse. 0 to deactivate
        * threads
            Total number of threads to use. 1 thread is used for the reader and 1 for the writer. Minimum 3(default = 4)
        * fields
            Columns to keep in the summary. None, the default, writes every
            field the bam files carry: run_id, channel, barcode_arrangement,
            sequence_length_template, mean_qscore_template, gc_percent,
            start_time, passes_filtering, flowcell_id, device_id,
            dorado_model, filename, sample_id and run_start_time. Naming a
            field that no bam carries is reported rather than ignored.
        * basecall_id
            id of the basecalling group. By default, leave to 0, but if you perform multiple basecalling on the same bam files,
            this can be used to indicate the corresponding group(1, 2 ...)
        * include_path
            If True the absolute path to the corresponding file is added in an extra column
        * verbose_level
            Level of verbosity, from 2(Chatty) to 0(Nothing)
        """
        # Set logging level
        logger.setLevel(logLevel_dict.get(verbose_level, logging.WARNING))

        # Perform checks
        logger.info("Check input data and options")
        if not os.access(bam_dir, os.R_OK):
            raise pycoQCError("Cannot read the indicated bam directory")
        # dirname of a bare name is "", which is never writable, so
        # a plain output filename was rejected.
        if not os.access(os.path.dirname(os.path.abspath(seq_summary_fn)), os.W_OK):
            raise pycoQCError("Cannot write the indicated seq_summary_fn")
        if threads < 3:
            raise pycoQCError("At least 3 threads required")

        # Save self args
        self.bam_dir = bam_dir
        self.seq_summary_fn = seq_summary_fn
        self.threads = threads - 2
        self.max_bam = max_bam
        self.fields = fields
        self.basecall_id = basecall_id
        self.include_path = include_path
        self.verbose_level = verbose_level

        # A BAM holds one basecall per record, not numbered groups the way a
        # FAST5 does, so there is nothing for this to select. It used to be
        # accepted and ignored in silence.
        if basecall_id:
            logger.warning(
                "WARNING: --basecall_id has no meaning for BAM input and is "
                "ignored; it selects one of several basecall groups inside a "
                "FAST5.")

        # List bam files in folder
        bam_list = self.list_bam(bam_dir, self.max_bam)
        print('Found {} bam files to process'.format(len(bam_list)))

        # Fetch relevant info from bam files in parallel
        master_bam_dict = dict()
        repeated = 0
        with ThreadPoolExecutor(max_workers=self.threads) as executor:
            for results in list(tqdm(executor.map(Bam_to_seq_summary.read_bam, bam_list),
                                     total=len(bam_list))):
                # Reads are collected by id, so a read present in two files
                # is written once. That is the right answer for a directory
                # holding both an aligned and an unaligned copy of a run, but
                # it used to happen in silence and the read count simply came
                # out lower than the files suggested.
                repeated += len(set(results).intersection(master_bam_dict))
                master_bam_dict.update(results)

        if repeated:
            logger.warning(
                "WARNING: {:,} read id(s) appear in more than one bam file and "
                "were written once. Check whether the directory holds the same "
                "run twice.".format(repeated))

        print('Writing "sequencing_summary" file...')
        Bam_to_seq_summary.write_seq_summary(
            master_bam_dict, self.seq_summary_fn, fields=self.fields,
            include_path=self.include_path)

        print('Done')

    @staticmethod
    def list_bam(bam_dir, max_bam):
        """
        Mono-threaded worker adding bam files found in a directory tree recursively
        to a feeder queue for the multiprocessing workers
        """
        logger.debug("[READER] Start listing bam files")
        bam_list = list()

        # Load an input queue with bam file path
        for i, bam_file in enumerate(recursive_file_gen(dir=bam_dir, ext='bam')):
            if max_bam and i == max_bam:
                break
            bam_list.append(bam_file)

        # Raise error is no file found
        if not bam_list:
            raise pycoQCError("No valid bam files found in indicated folder")

        logger.debug("[READER] Add a total of {} files to input queue".format(len(bam_list)))

        return bam_list

    @staticmethod
    def parse_read_groups(header):
        """Map each @RG ID to the run metadata it carries

        A barcoded run has one read group per barcode, so each read is looked
        up by its own RG rather than assuming one group for the whole file.
        Every field is optional: a BAM from another tool may carry none of
        them, and missing values should leave a blank column rather than
        stopping the run.

        * header
            A pysam AlignmentHeader.
        """
        groups = dict()
        for rg in header.to_dict().get("RG", []):
            rg_id = rg.get("ID", "")
            # DS is a space separated list of key=value pairs, so read it by
            # name. Taking the first pair put the run id in the model column,
            # since Oxford Nanopore list runid before basecall_model.
            ds = dict()
            for part in rg.get("DS", "").split():
                key, sep, value = part.partition("=")
                if sep:
                    ds[key] = value
            groups[rg_id] = {
                "run_id": ds.get("runid") or rg_id.split("_")[0],
                "flowcell_id": rg.get("PU", ""),
                "device_id": rg.get("PM", ""),
                "dorado_model": ds.get("basecall_model", ""),
                # Dorado writes the barcode as a BC tag on the read, while the
                # Oxford Nanopore output spec puts it on the read group as SM,
                # with al holding the sample-sheet alias.
                "barcode": rg.get("SM") or rg.get("al") or "",
                "sample_id": rg.get("LB", ""),
                # DT is the protocol start time, which is what answers
                # "when was this run?" in the report.
                "run_start_time": rg.get("DT", ""),
            }
        return groups

    @staticmethod
    def read_bam(bam_file):

        logger.debug("[WORKER] Start processing bam files")

        entry_dict = dict()

        with pysam.AlignmentFile(bam_file, "rb", check_sq=False) as fh:
            # Read groups are a property of the file, so parse them once
            # rather than re-parsing the header text for every read.
            read_groups = Bam_to_seq_summary.parse_read_groups(fh.header)
            # Must carry every key the loop below reads, or a BAM whose
            # reads have no matching @RG raises KeyError instead of the
            # blanks the docstring promises.
            blank_group = {"run_id": "", "flowcell_id": "", "device_id": "",
                           "dorado_model": "", "barcode": "", "sample_id": "",
                           "run_start_time": ""}

            for bam_entry in fh.fetch(until_eof=True):
                # One read can have several records once the BAM is aligned.
                # Only the primary alignment carries the full sequence: a
                # supplementary record is hard clipped, and a secondary one
                # often has no SEQ at all. Counting them overwrote the read
                # with a fragment of itself, or crashed on the missing
                # sequence.
                if bam_entry.is_secondary or bam_entry.is_supplementary:
                    continue

                bam_dict = dict()
                read_id = bam_entry.query_name

                tags = bam_entry.tags  # List of tuples
                """
                BC:
                qs:i:10  # Q-score
                du:f:31.6362  # Duration of the read (in seconds)
                ns:i:126545  # Number of signals prior trimming
                ts:i:170  # Number of signals trimmed from start
                mx:i:1  # read mux
                ch:i:5  # Channel
                st:Z:2021-03-29T15:18:10.066+00:00  # Start time
                rn:i:6347  # read number
                fn:FAW88668_pass_barcode06_1ec22c6e_7ac59ce2_5.pod5  # File name
                sm:f:98.1631  # scaling midpoint/mean/median (pA to ~0-mean/1-sd)
                sd:f:13.5198  # scaling dispersion (pA to ~0-mean/1-sd)
                sv:Z:med_mad  # scaling version
                dx:i:0  # 
                RG:Z:e2419f1214664b2b48a1f01eebf8dfa6f28fb57a_dna_r9.4.1_e8_sup@v3.3  # <runid>_<basecalling_model>
                """
                tags_of_interest = ['BC', 'qs', 'du', 'ch', 'st', 'rn', 'fn', 'RG']
                for tag_tuple in tags:
                    tag, value = tag_tuple
                    if tag in tags_of_interest:
                        bam_dict[tag] = value
                seq = bam_entry.query_sequence
                length = bam_entry.query_length
                qual = bam_entry.query_qualities

                group = read_groups.get(bam_dict.get('RG', ''), blank_group)
                run_id = group["run_id"]
                flowcell = group["flowcell_id"]
                sequencer = group["device_id"]
                model = group["dorado_model"]
                run_start = group["run_start_time"]
                sample_id = group["sample_id"]

                # st and ch are required by the spec but a BAM from another
                # tool may lack them, and a missing value should not stop the
                # whole run.
                start_time = bam_dict.get('st')
                time_string = parse_timestamp(start_time) if start_time else ''
                channel = bam_dict.get('ch', '')

                # Dorado writes a BC tag; MinKNOW puts the barcode on the read
                # group instead.
                # An absent barcode is not a barcode. Writing the string
                # "none" made a run with no barcoding look like a barcoded
                # run with one sample called none, and the fastq converter
                # already wrote an empty value for the same situation.
                barcode = bam_dict.get('BC') or group["barcode"] or ''

                # fn is a Dorado extension holding the source file name and is
                # absent from the Oxford Nanopore output spec, so fall back to
                # the path of the BAM itself, which carries pass or fail in the
                # directory name the basecaller writes.
                file_name = bam_dict.get('fn') or os.path.basename(bam_file)
                location = file_name if bam_dict.get('fn') else bam_file

                # Flag, matched on whole words so a path such as
                # /data/failover/bam_pass is not read as failing.
                if path_has_token(location, 'fail'):
                    flag = 'FALSE'
                else:
                    flag = 'TRUE'

                # Average phred score
                average_phred = round(mean_qscore(qual), 2)

                # %GC. A record can carry no sequence, and a zero length
                # read is valid input, so neither should divide by zero or
                # count characters of None.
                if seq and length:
                    gc = round((seq.count('G') + seq.count('C'))
                               / float(length) * 100, 2)
                else:
                    gc = 0.0

                # Output everything in a dictionary
                entry_dict[read_id] = dict()
                entry_dict[read_id]['run_id'] = run_id
                entry_dict[read_id]['channel'] = channel
                entry_dict[read_id]['barcode_arrangement'] = barcode
                entry_dict[read_id]['sequence_length_template'] = length
                entry_dict[read_id]['mean_qscore_template'] = average_phred
                entry_dict[read_id]['gc_percent'] = gc
                entry_dict[read_id]['start_time'] = time_string
                entry_dict[read_id]['passes_filtering'] = flag
                entry_dict[read_id]['flowcell_id'] = flowcell
                entry_dict[read_id]['device_id'] = sequencer
                entry_dict[read_id]['dorado_model'] = model
                entry_dict[read_id]['filename'] = file_name
                entry_dict[read_id]['sample_id'] = sample_id
                entry_dict[read_id]['run_start_time'] = run_start
                entry_dict[read_id]['path'] = os.path.abspath(bam_file)

        return entry_dict

    @staticmethod
    def write_seq_summary(bam_dict, output_file, fields=None,
                          include_path=False):
        """
        Mono-threaded Worker writing the sequencing summary file

        * fields
            Columns to keep, read_id aside. None writes everything a BAM
            carries. Both this and include_path were stored and never read,
            so --fields and --include_path were accepted and did nothing.
        * include_path
            Keep the path of the file each read came from.
        """
        logger.debug("[WRITER] Write data to file")

        # A directory can hold a bam with nothing in it: an empty bam_fail
        # for a barcode that never failed, for instance. That used to reach
        # pandas as an empty frame and come back as KeyError: 'start_time'.
        if not bam_dict:
            raise pycoQCError(
                "No reads found in the bam file(s). The files were read but "
                "hold no primary alignments.")

        # Convert dictionary to dataframe
        df = pd.DataFrame.from_dict(bam_dict, orient='index')
        df.index.names = ['read_id']

        if fields:
            wanted = [f for f in fields if f != "read_id"]
            missing = [f for f in wanted if f not in df.columns]
            if missing:
                logger.warning(
                    "WARNING: a BAM carries no {}, so {} left out of the "
                    "summary".format(
                        "field called" if len(missing) == 1 else "fields called",
                        ", ".join(missing)))
            keep = [f for f in wanted if f in df.columns]
            if include_path and "path" in df.columns and "path" not in keep:
                keep.append("path")
            df = df[keep]
        elif not include_path:
            df = df.drop(columns="path", errors="ignore")

        # Express read start times as seconds since their own run began. A
        # directory can hold several runs, and counting from the first read
        # of the whole directory charged the gap between them to the later
        # one: two one hour runs two days apart were reported as 50 hours.
        elapsed_seconds_per_run(df)

        df.to_csv(output_file, sep="\t", index=True, header=True)
